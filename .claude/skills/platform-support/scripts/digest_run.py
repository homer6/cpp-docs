#!/usr/bin/env python3
"""Digest every job log of a GitHub Actions run, for the platform-support skill.

The raw logs are never stored (the owner's rule), so this pulls out what the
results JSON doesn't carry: compiler and linker errors, crashes and timeouts,
failed steps, and warnings, per job and across jobs. Test failures and skip
reasons come from the results JSON (tools/collect_results.py); this is for
everything else in the logs.

    digest_run.py <run-id> [<run-id> ...] [--out FILE] [--repo OWNER/NAME]
    digest_run.py --self-test

Read-only: it uses `gh api` to list jobs and fetch each job's log. It writes a
Markdown digest (stdout, or --out, normally the scratchpad, never the repo).
"""
import argparse
import json
import re
import subprocess
import sys
from collections import Counter, defaultdict

REPO = "homer6/cpp-docs"

# "2026-11-02T00:22:19.9601994Z " at the start of every log line.
STAMP = re.compile(r"^\ufeff?\d{4}-\d\d-\d\dT[\d:.]+Z ?")
# Paths differ per runner; keep the repo-relative part.
PATH = re.compile(r"(?:[A-Za-z]:)?[\\/][^\s:()]*?[\\/]cpp-docs[\\/]cpp-docs[\\/]")
ESC = re.compile(r"\x1b\[[0-9;]*m")

ERROR = re.compile(
    r"(?:\berror C\d{4}\b|\berror LNK\d{4}\b|\bfatal error\b|(?<![-\w])error:|"
    r"lld-link: error|ld(?:\.lld)?: error|undefined reference to|"
    r"Undefined symbols for architecture)")
WARNING = re.compile(r"(?:\bwarning C\d{4}\b|(?<![-\w])warning:)")
WFLAG = re.compile(r"\[(-W[\w+=-]+)\]")
WCODE = re.compile(r"\bwarning (C\d{4})\b")
CRASH = re.compile(r"\((SEGFAULT|Subprocess aborted|Timeout|Exception|ILLEGAL|Bus error|"
                   r"Child aborted|Not Run)\)|\b(Segmentation fault|Bus error|Abort trap|"
                   r"terminate called|AddressSanitizer|UndefinedBehaviorSanitizer)\b")
FAILED_CMD = re.compile(r"^FAILED: (?:\[code=-?\d+\] )?(\S+)")
STEP_ERROR = re.compile(r"##\[error\](.*)")
NOISE = re.compile(r"error(?:s)? generated|^\s*\d+ errors?\b|Error: Process completed|"
                   r"ninja: build stopped|-Werror|error_code|errorlevel|\berror\.(?:cpp|hpp|md)|"
                   r"/errors?/|_error|error-|error\w")


def clean(line):
    return PATH.sub("", ESC.sub("", STAMP.sub("", line))).rstrip()


def digest_log(text):
    """Return the findings of one job log as a dict."""
    errors, warnings, crashes, failed, steps = [], Counter(), [], [], []
    wexample = {}
    seen = set()
    for raw in text.splitlines():
        # Logs from `gh run view --log` carry "<job>\t<step>\t" first.
        line = clean(raw.split("\t")[-1])
        if not line.strip():
            continue
        m = STEP_ERROR.search(line)
        if m:
            steps.append(m.group(1).strip())
            continue
        m = FAILED_CMD.match(line)
        if m:
            failed.append(m.group(1))
            continue
        if CRASH.search(line):
            crashes.append(line.strip())
            continue
        if ERROR.search(line) and not (NOISE.search(line) and "error:" not in line and
                                       not re.search(r"error (C|LNK)\d", line)):
            key = line.strip()
            if key not in seen:
                seen.add(key)
                errors.append(key)
            continue
        if WARNING.search(line):
            m = WFLAG.search(line) or WCODE.search(line)
            code = m.group(1) if m else "warning"
            warnings[code] += 1
            wexample.setdefault(code, line.strip())
    return {"errors": errors, "warnings": warnings, "warning_examples": wexample,
            "crashes": list(dict.fromkeys(crashes)), "failed_targets": list(dict.fromkeys(failed)),
            "step_errors": list(dict.fromkeys(steps))}


def gh(*args):
    return subprocess.run(["gh", *args], check=True, capture_output=True, text=True).stdout


def jobs_of(run, repo):
    out = gh("api", f"repos/{repo}/actions/runs/{run}/jobs?per_page=100", "--paginate",
             "--jq", ".jobs[] | {id, name, conclusion, html_url}")
    return [json.loads(l) for l in out.splitlines() if l.strip()]


def job_log(job_id, repo):
    try:
        return gh("api", f"repos/{repo}/actions/jobs/{job_id}/logs")
    except subprocess.CalledProcessError as e:  # expired or not yet available
        return f"##[error]log unavailable: {e.stderr.strip()}"


def short(msg, n=220):
    return msg if len(msg) <= n else msg[: n - 1] + "…"


def render(runs):
    out = ["# Run digest", "",
           "Generated by `.claude/skills/platform-support/scripts/digest_run.py`. Process every "
           "finding (platform-support skill, step 3); don't commit this file.", ""]
    by_error = defaultdict(list)
    for run, jobs in runs:
        for job, d in jobs:
            for e in d["errors"]:
                by_error[re.sub(r"\(\d+\)|:\d+:\d+:|:\d+:", ":", e)].append(job["name"])
    if by_error:
        out += ["## Errors across jobs", "", "| Error | Jobs |", "|---|---|"]
        for e, names in sorted(by_error.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            names = list(dict.fromkeys(names))
            out.append(f"| `{short(e).replace('|', '\\|')}` | {len(names)}: "
                       f"{', '.join(names[:6])}{' …' if len(names) > 6 else ''} |")
        out.append("")
    for run, jobs in runs:
        out += [f"## Run {run}", ""]
        out += ["| Job | Conclusion | Errors | Crashes | Failed targets | Warnings |",
                "|---|---|---|---|---|---|"]
        for job, d in jobs:
            out.append(f"| [{job['name']}]({job.get('html_url', '')}) | {job.get('conclusion')} | "
                       f"{len(d['errors'])} | {len(d['crashes'])} | {len(d['failed_targets'])} | "
                       f"{sum(d['warnings'].values())} |")
        out.append("")
        for job, d in jobs:
            if not (d["errors"] or d["crashes"] or d["failed_targets"] or d["step_errors"]
                    or d["warnings"]):
                continue
            out += [f"### {job['name']} ({job.get('conclusion')})", ""]
            for title, items in (("Step errors", d["step_errors"]), ("Failed targets", d["failed_targets"]),
                                 ("Crashes", d["crashes"]), ("Errors", d["errors"])):
                if items:
                    out.append(f"**{title}**")
                    out += [f"- `{short(i)}`" for i in items[:40]]
                    if len(items) > 40:
                        out.append(f"- … {len(items) - 40} more")
                    out.append("")
            if d["warnings"]:
                out.append("**Warnings** (count, first example)")
                for code, n in d["warnings"].most_common(15):
                    out.append(f"- {code} ×{n}: `{short(d['warning_examples'][code])}`")
                out.append("")
    return "\n".join(out) + "\n"


SAMPLE = """2026-11-02T00:22:19.9601994Z FAILED: [code=2] tests/CMakeFiles/x.dir/a_test.cpp.obj
2026-11-02T00:22:20.0295448Z D:\\a\\cpp-docs\\cpp-docs\\tests\\a_test.cpp(69): error C2065: 'nodiscard': undeclared identifier
2026-11-02T00:22:20.0295448Z D:\\a\\cpp-docs\\cpp-docs\\tests\\a_test.cpp(69): error C2065: 'nodiscard': undeclared identifier
2026-11-02T00:22:21.0Z /home/runner/work/cpp-docs/cpp-docs/tests/b_test.cpp:12:3: warning: unused variable 'x' [-Wunused-variable]
2026-11-02T00:22:21.0Z /home/runner/work/cpp-docs/cpp-docs/tests/c_test.cpp:9:1: warning: unused variable 'y' [-Wunused-variable]
2026-11-02T00:22:22.0Z D:\\a\\cpp-docs\\cpp-docs\\tests\\d_test.cpp(3): warning C4127: conditional expression is constant
2026-11-02T00:22:23.0Z lld-link: error: duplicate symbol: int __cdecl step(void)
2026-11-02T00:22:24.0Z  42 - Suite.Name (SEGFAULT)
2026-11-02T00:22:25.0Z 2 errors generated.
2026-11-02T00:22:25.0Z ninja: build stopped: subcommand failed.
2026-11-02T00:22:25.0Z [ RUN      ] ErrorCode.Message
2026-11-02T00:22:26.0Z ##[error]Process completed with exit code 1.
"""


def self_test():
    d = digest_log(SAMPLE)
    checks = [
        (d["failed_targets"] == ["tests/CMakeFiles/x.dir/a_test.cpp.obj"], "failed target"),
        (d["errors"] == ["tests\\a_test.cpp(69): error C2065: 'nodiscard': undeclared identifier",
                         "lld-link: error: duplicate symbol: int __cdecl step(void)"], f"errors {d['errors']}"),
        (d["warnings"] == Counter({"-Wunused-variable": 2, "C4127": 1}), f"warnings {d['warnings']}"),
        (len(d["crashes"]) == 1 and "SEGFAULT" in d["crashes"][0], "crash"),
        (d["step_errors"] == ["Process completed with exit code 1."], "step error"),
    ]
    md = render([("1", [({"name": "job", "conclusion": "failure", "html_url": "u"}, d)])])
    checks.append(("Errors across jobs" in md and "C2065" in md, "render"))
    bad = [msg for ok, msg in checks if not ok]
    for msg in bad:
        print("FAIL:", msg)
    print(f"digest_run self-test: {'OK' if not bad else 'FAILED'} ({len(bad)} failure(s))")
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("runs", nargs="*")
    ap.add_argument("--repo", default=REPO)
    ap.add_argument("--out")
    ap.add_argument("--failed-only", action="store_true", help="skip jobs that succeeded")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()
    if not a.runs:
        ap.error("give one or more run IDs")
    runs = []
    for run in a.runs:
        jobs = []
        for job in jobs_of(run, a.repo):
            if a.failed_only and job.get("conclusion") == "success":
                continue
            jobs.append((job, digest_log(job_log(job["id"], a.repo))))
        runs.append((run, jobs))
    md = render(runs)
    if a.out:
        with open(a.out, "w") as f:
            f.write(md)
        print(f"wrote {a.out}")
    else:
        sys.stdout.write(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
